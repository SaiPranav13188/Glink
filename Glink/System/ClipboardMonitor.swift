import AppKit
import CryptoKit
import Observation
import SwiftData

/// Watches NSPasteboard.general.changeCount every ~0.5s and stores new items.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    /// Types that password managers and well-behaved apps use to say "don't record this".
    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardMonitor.shared.poll() }
        }
        t.tolerance = 0.2   // lets macOS coalesce wakeups so idle CPU stays ~0%
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let store = ClipboardStore.shared
        guard AppSettings.shared.clipboardEnabled, !store.shouldIgnore(changeCount: pb.changeCount) else { return }

        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.privateTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication
        if let id = source?.bundleIdentifier, AppSettings.shared.ignoredBundleIDs.contains(id) { return }
        store.capture(from: pb, sourceApp: source)
    }
}

/// Clipboard history persisted with SwiftData.
@MainActor @Observable
final class ClipboardStore {
    static let shared = ClipboardStore()

    private(set) var entries: [ClipboardEntry] = []
    @ObservationIgnored private var ignoredChangeCount = -1
    private var context: ModelContext { DataStore.shared.context }

    private init() { reload() }

    func reload() {
        let descriptor = FetchDescriptor<ClipboardEntry>(sortBy: [SortDescriptor(\.createdAt, order: .reverse)])
        entries = (try? context.fetch(descriptor)) ?? []
    }

    /// Call right after Glink itself writes to the pasteboard so its own copies aren't recorded twice.
    func ignoreCurrentChange() { ignoredChangeCount = NSPasteboard.general.changeCount }
    func shouldIgnore(changeCount: Int) -> Bool { changeCount == ignoredChangeCount }

    func capture(from pb: NSPasteboard, sourceApp: NSRunningApplication?) {
        let bundleID = sourceApp?.bundleIdentifier
        let appName = sourceApp?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            insert(ClipboardEntry(kind: .file, filePaths: paths, sourceBundleID: bundleID, sourceAppName: appName,
                                  contentHash: hash("file:" + paths.joined(separator: "\n"))))
            return
        }

        if let imageType = pb.availableType(from: [.png, .tiff]), let raw = pb.data(forType: imageType), raw.count < 25_000_000 {
            let png: Data
            var size = CGSize.zero
            if let rep = NSBitmapImageRep(data: raw) {
                size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
                png = imageType == .png ? raw : (rep.representation(using: .png, properties: [:]) ?? raw)
            } else {
                png = raw
            }
            insert(ClipboardEntry(kind: .image, imageData: png, sourceBundleID: bundleID, sourceAppName: appName,
                                  contentHash: hash(png), imageSize: size))
            return
        }

        guard let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        var kind = ClipKind.text
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
           ["http", "https"].contains(scheme), url.host != nil {
            kind = .link
        } else if trimmed.range(of: "^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$", options: .regularExpression) != nil {
            kind = .color
        }
        insert(ClipboardEntry(kind: kind, text: String(string.prefix(500_000)), sourceBundleID: bundleID,
                              sourceAppName: appName, contentHash: hash("text:" + string)))
    }

    private func insert(_ entry: ClipboardEntry) {
        // Copying the same thing again moves it to the top instead of duplicating it.
        if let existing = entries.first(where: { $0.contentHash == entry.contentHash }) {
            existing.createdAt = Date()
            existing.sourceAppName = entry.sourceAppName ?? existing.sourceAppName
        } else {
            context.insert(entry)
        }
        trimToLimit()
        DataStore.shared.save()
        reload()
    }

    private func trimToLimit() {
        let limit = AppSettings.shared.clipboardHistoryLimit
        let unpinned = ((try? context.fetch(FetchDescriptor<ClipboardEntry>(
            predicate: #Predicate { !$0.isPinned },
            sortBy: [SortDescriptor(\.createdAt, order: .reverse)]))) ?? [])
        for entry in unpinned.dropFirst(limit) { context.delete(entry) }
    }

    func delete(_ entry: ClipboardEntry) {
        context.delete(entry)
        DataStore.shared.save()
        reload()
    }

    func togglePin(_ entry: ClipboardEntry) {
        entry.isPinned.toggle()
        DataStore.shared.save()
        reload()
    }

    func clearAll(keepPinned: Bool = true) {
        for e in entries where !(keepPinned && e.isPinned) { context.delete(e) }
        DataStore.shared.save()
        IconCache.shared.clear()
        reload()
    }

    func entry(id: UUID) -> ClipboardEntry? { entries.first { $0.id == id } }
    func imageData(for id: UUID) -> Data? { entry(id: id)?.imageData }

    /// Puts an entry back on the pasteboard with its original kind.
    func write(_ entry: ClipboardEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.kind {
        case .image:
            if let data = entry.imageData { pb.setData(data, forType: .png) }
        case .file:
            pb.writeObjects(entry.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
        default:
            pb.setString(entry.text ?? "", forType: .string)
        }
        ignoreCurrentChange()
        entry.createdAt = Date()
        DataStore.shared.save()
        reload()
    }

    func search(_ query: String) -> [ClipboardEntry] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return entries }
        return entries.filter {
            ($0.text?.localizedCaseInsensitiveContains(q) ?? false)
                || $0.filePaths.contains { $0.localizedCaseInsensitiveContains(q) }
                || ($0.sourceAppName?.localizedCaseInsensitiveContains(q) ?? false)
                || $0.kind.title.localizedCaseInsensitiveContains(q)
        }
    }

    private func hash(_ string: String) -> String { hash(Data(string.utf8)) }
    private func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
